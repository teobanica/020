#!/usr/bin/env python3
"""Exact, independent checks of the common-support BBB extension certificates.

No numerical sampling. Monomials have seven integral parameter exponents and
one root exponent modulo 840. Verification checks saved positive certificates,
the two complete scan outputs, and their reduction to the stated circles.
Exhaustive exclusion additionally relies on the scans regenerated by run.py.
"""
from collections import Counter
from functools import lru_cache
from itertools import permutations, product
from math import factorial
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parent
M = 840
PROFILES = {'B': (7, 2, 2), 'C': (5, 3, 3), 'D': (5, 2, 2, 2),
            'E': (3, 3, 3, 2), 'F': (3, 2, 2, 2, 2)}
EXPECTED = {'B': (712800, 2964, 1420), 'C': (443520, 0, 0),
            'D': (166320, 0, 0), 'E': (123200, 0, 0), 'F': (34650, 59136, 0)}


def records(name):
    return [tuple(map(int, line.split())) for line in (ROOT / name).read_text().splitlines()]


def monomial(q=0, s=0, t=0, e=0, group=0):
    assert 0 <= group <= 4
    return (q, s, t, *(int(group == k) for k in range(1, 5)), e % M)


def quotient(x, y):
    return tuple(tuple(a - b for a, b in zip(u[:-1], v[:-1])) + ((u[-1] - v[-1]) % M,)
                 for u, v in zip(x, y))


def decode(key):
    assert len(key) == 67 and key[:12] == (0,) * 12
    row = tuple(monomial(q, s, t, e, g) for g, q, s, t, e in
                (key[i:i + 5] for i in range(12, 67, 5)))
    assert row[0] == monomial()
    return row


def cover(row, profile=None):
    """Find literal prime cycles using monomial equality, independently of C++."""
    row = tuple(row)
    positions = {}
    for j, x in enumerate(row):
        positions.setdefault(x, []).append(j)
    wanted = tuple(sorted(profile or (), reverse=True))

    @lru_cache(None)
    def visit(mask, sizes):
        if not mask:
            return () if not sizes else None
        j = (mask & -mask).bit_length() - 1
        x = row[j]
        primes = sorted(set(sizes), reverse=True) if profile else (7, 5, 3, 2)
        for p in primes:
            if p > mask.bit_count():
                continue
            choices = [[k for k in positions.get(x[:-1] + ((x[-1] + M // p * a) % M,), ())
                        if mask >> k & 1] for a in range(1, p)]
            for others in product(*choices):
                block = (j,) + others
                assert len(set(block)) == p
                next_sizes = list(sizes)
                if profile:
                    next_sizes.remove(p)
                result = visit(mask ^ sum(1 << k for k in block), tuple(next_sizes))
                if result is not None:
                    return (block,) + result
        return None

    return visit((1 << len(row)) - 1, wanted)


def count_presentations(sizes):
    # Unlabelled equal-size blocks; each first column is the root-label zero.
    answer = factorial(11)
    for p in sizes:
        answer //= p
    for multiplicity in Counter(sizes).values():
        answer //= factorial(multiplicity)
    return answer


def main():
    if sys.flags.optimize:
        raise RuntimeError('Run without -O: assertions are part of this verifier.')
    heads = [(0,) + f for f in permutations(range(1, 7))
             if len({(x - j) % 7 for j, x in enumerate((0,) + f)}) == 7]
    assert len(heads) == 19 and records('head_rows.txt') == heads
    linear = {i: a for i, f in enumerate(heads) for a in range(2, 7)
              if f == tuple(a * j % 7 for j in range(7))}
    assert len(linear) == 5
    edges = [(i, j) for i, f in enumerate(heads) for j, g in enumerate(heads[:i])
             if len({(a - b) % 7 for a, b in zip(f, g)}) == 7]
    assert set(edges) == {(i, j) for i in linear for j in linear if i > j}
    one = (monomial(),) * 11
    u = tuple(monomial(e=120 * j) for j in range(7)) + (
        monomial(s=1), monomial(s=1, e=420),
        monomial(q=1, s=1), monomial(q=1, s=1, e=420))
    assert records('base_pair.txt') == [(2 * j, 0, 0, 0) for j in range(7)] + [
        (0, 0, 1, 0), (7, 0, 1, 0), (0, 1, 1, 0), (7, 1, 1, 0)]
    old = []
    for f in heads:
        v = tuple(monomial(e=120 * j) for j in f) + tuple(
            monomial(t=1, e=420 * int(j >= 2)) for j in range(4))
        old.append(v)
        for x, y in ((u, one), (v, one), (u, v)):
            assert cover(quotient(x, y), PROFILES['B']) is not None

    counts, exception_set, circle_keys, fixed = {}, set(), set(), 0
    for profile in PROFILES:
        scans = []
        for mode in ('primary', 'audit'):
            name = f'{mode}_{profile}'
            pairs, finals = records(name + '.txt.pairs'), records(name + '.txt')
            assert len(pairs) == len(set(pairs)) and len(finals) == len(set(finals))
            log = (ROOT / (name + '.log')).read_text()
            match = re.search(r'^tests (\d+) pairs (\d+) final (\d+) nodes ', log, re.M)
            assert match is not None
            result = tuple(map(int, match.groups()))
            assert result == EXPECTED[profile]
            assert result == (count_presentations(PROFILES[profile]), len(pairs), len(finals))
            scans.append((set(pairs), set(finals)))
        assert scans[0] == scans[1]
        pairs, finals = scans[0]
        if profile == 'B':
            assert Counter(r[0] for r in finals) == Counter({i: 284 for i in linear})
        for key in pairs:
            x = decode(key)
            assert cover(x, PROFILES[profile]) is not None
            assert cover(quotient(x, u)) is not None
        for record in finals:
            i, key = record[0], record[1:]
            assert i in linear
            x = decode(key)
            for y in (one, u, old[i]):
                assert cover(quotient(x, y), PROFILES['B']) is not None
            k = x[1][-1] // 120
            assert k in set(range(2, 7)) - {linear[i]}
            assert x[:7] == tuple(monomial(e=120 * k * j) for j in range(7))
            tail = quotient(x[7:], (x[7],) * 4)
            assert tail == (monomial(), monomial(e=420),
                            monomial(q=1, e=420), monomial(q=1))
            groups = tuple(key[j] for j in range(12, 67, 5))
            if max(groups):
                assert groups == (0,) * 7 + (1,) * 4
                assert x[7] == monomial(group=1)
                circle_keys.add((i, k))
            else:
                fixed += 1
        ex = records(f'audit_{profile}.txt.exceptional')
        assert len(ex) == len(set(ex))
        for a, b, c, e in ex:
            assert (a, b, c) != (0, 0, 0) and 0 <= e < M
            assert next(x for x in (a, b, c) if x) > 0
            assert e % 4 == 0 and max(abs(a), abs(b), abs(c)) <= 4
        exception_set.update(ex)
        counts[profile] = {'presentations': EXPECTED[profile][0],
                           'pair_records': len(pairs), 'triple_records': len(finals),
                           'exceptional_equations': len(ex)}
        print(profile, counts[profile], flush=True)
    assert fixed == 1400
    assert circle_keys == {(i, k) for i, a in linear.items() for k in range(2, 7) if k != a}

    # The retained exceptional B/D pair witness, specialized over mu_70.
    witness = records('witness_D.txt')[0]
    assert witness[:12] == (1, 0, 0, 588, 0, 1, 0, 408, 0, 0, 0, 0)
    x = tuple(monomial(e=q * 588 + s * 408 + e) for g, q, s, t, e in
              (witness[j:j + 5] for j in range(12, 67, 5)))
    assert all(witness[j] == 0 and witness[j + 3] == 0 for j in range(12, 67, 5))
    specialized_u = tuple(monomial(e=v[0] * 588 + v[1] * 408 + v[-1]) for v in u)
    rows = (one, specialized_u, x)
    certificates = {}
    for i in range(3):
        for j in range(i):
            r = quotient(rows[i], rows[j])
            certificates[f'{i}/{j}'] = {p: c for p, sizes in PROFILES.items()
                                         if (c := cover(r, sizes)) is not None}
            assert certificates[f'{i}/{j}']
    assert 'B' in certificates['1/0'] and 'D' in certificates['2/0']
    assert all(v[-1] % 12 == 0 for row in rows for v in row)
    summary = {'scope': 'Displayed T_f(q,s,t), outside the recorded exceptional union.',
               'heads': len(heads), 'linear_heads': linear, 'head_graph_edges': edges,
               'counts': counts, 'circles': sorted(circle_keys), 'fixed_specializations': fixed,
               'exceptional_equations_union': len(exception_set),
               'max_exceptional_coefficient': max(abs(a) for v in exception_set for a in v[:3]),
               'witness_level': 70, 'witness_exponents': [[v[-1] // 12 for v in row] for row in rows],
               'witness_covers': certificates, 'passed': True}
    assert len(exception_set) == 3038
    (ROOT / 'exceptional_union.txt').write_text(''.join(
        f'{a} {b} {c} {e // 4}\n' for a, b, c, e in sorted(exception_set)))
    (ROOT / 'verification.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
